//go:build tools

// This integration-only generator keeps the generated test client out of
// ordinary builds, where it would otherwise pull in the consumer fixture.
package main

import (
	"log"

	"entgo.io/ent/entc"
	"entgo.io/ent/entc/gen"
)

func main() {
	err := entc.Generate(
		"github.com/huynhanx03/go-common/pkg/toggle/ent/testschema",
		&gen.Config{
			Target:     "pkg/toggle/ent/internal/testent",
			Package:    "github.com/huynhanx03/go-common/pkg/toggle/ent/internal/testent",
			BuildFlags: []string{"-tags=integration"},
			Header:     "//go:build integration\n\n// Code generated by ent, DO NOT EDIT.",
		},
	)
	if err != nil {
		log.Fatal(err)
	}
}
