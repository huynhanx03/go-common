package kit

import (
	"context"
	"io"
	"time"
)

// Options configures the comxkit command tree.
type Options struct {
	In            io.Reader
	Out           io.Writer
	Err           io.Writer
	WorkDir       string
	Version       string
	CommonVersion string
	Interactive   bool
}

// InitInput describes a new application project.
type InitInput struct {
	Directory     string
	Module        string
	HTTP          string
	ORM           string
	Database      string
	CommonVersion string
}

// DomainInput describes a domain boundary to add to a project.
type DomainInput struct {
	Name string
}

// ResourceInput describes a CRUD resource to add to a domain.
type ResourceInput struct {
	Name       string
	Domain     string
	Route      string
	UpsertOn   string
	Operations []string
	SoftDelete bool
	Modifier   bool
}

// PlannedFile is a project-relative file generated by a plan.
type PlannedFile struct {
	Path         string
	Content      []byte
	ExpectedHash string
	Owned        bool
}

// Plan contains files and metadata changes that can be applied together.
type Plan struct {
	Root                 string
	Kind                 string
	Files                []PlannedFile
	Metadata             *projectMetadata
	ExpectedMetadataHash string
	NoOp                 bool
}

// Result describes the project files changed by a completed plan.
type Result struct {
	Root    string
	Created []string
	Updated []string
	NoOp    bool
}

type generator interface {
	Init(context.Context, InitInput) (Plan, error)
	Domain(context.Context, string, DomainInput) (Plan, error)
	Resource(context.Context, string, ResourceInput) (Plan, error)
	Apply(context.Context, Plan) (Result, error)
}

type prompter interface {
	Project(context.Context, InitInput, Registry) (InitInput, error)
	Resource(context.Context, ResourceInput, Registry) (ResourceInput, error)
	Confirm(context.Context, Plan) (bool, error)
}

// projectMetadata is persisted in generated projects and extended by the
// project generator as ownership and registration contracts are added.
type projectMetadata struct {
	Version     int               `yaml:"version"`
	Generator   string            `yaml:"generator,omitempty"`
	Module      string            `yaml:"module"`
	HTTP        string            `yaml:"http"`
	ORM         string            `yaml:"orm"`
	Database    string            `yaml:"database"`
	Schema      string            `yaml:"schema"`
	Domains     []string          `yaml:"domains,omitempty"`
	Resources   []resourceRecord  `yaml:"resources,omitempty"`
	GeneratedAt time.Time         `yaml:"generated_at,omitempty"`
	Files       map[string]string `yaml:"files,omitempty"`
}

type resourceRecord struct {
	Domain     string   `yaml:"domain"`
	Name       string   `yaml:"name"`
	Route      string   `yaml:"route"`
	Operations []string `yaml:"operations"`
	SoftDelete bool     `yaml:"soft_delete,omitempty"`
	Modifier   bool     `yaml:"modifier,omitempty"`
}
